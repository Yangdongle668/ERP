CREATE TABLE qc_aql_code (
    id                 BIGINT        NOT NULL PRIMARY KEY,
    lot_min BIGINT NOT NULL COMMENT '批量下限（含）',
    lot_max BIGINT NULL COMMENT '批量上限（含），空表示及以上',
    inspection_level VARCHAR(4) NOT NULL COMMENT 'S1/S2/S3/S4/I/II/III',
    code_letter VARCHAR(2) NOT NULL COMMENT '样本量字码',
    version            INT           NOT NULL DEFAULT 0,
    created_by         BIGINT        NULL,
    created_at         DATETIME      NOT NULL,
    updated_by         BIGINT        NULL,
    updated_at         DATETIME      NOT NULL,
    deleted            TINYINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_qc_aql_code UNIQUE (lot_min, inspection_level)
) COMMENT 'AQL 样本量字码表（表 1）';

