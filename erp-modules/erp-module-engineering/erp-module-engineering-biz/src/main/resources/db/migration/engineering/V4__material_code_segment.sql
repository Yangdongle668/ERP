-- 物料编码段（需求 05-01 第 8 节、05-02 R14）：编码 = 类别前缀 + 各编码段的特征值 + 流水号，
-- 如线材 12- + 线材型号 02 + 颜色 1 + 5 位流水 = 12-02100001。不同特征组合独立计数。

ALTER TABLE eng_material_category ADD COLUMN code_seq_length INT NULL COMMENT '流水号位数，空则按编码规则（5 位）';
ALTER TABLE eng_material ADD COLUMN code_segments VARCHAR(512) NULL COMMENT '编码构成（生成时的编码段取值，展示用）';

CREATE TABLE eng_code_segment (
    id          BIGINT       NOT NULL PRIMARY KEY,
    category_id BIGINT       NOT NULL COMMENT '物料类别（末级）',
    name        VARCHAR(32)  NOT NULL COMMENT '编码段名称，如 线材型号',
    seg_length  INT          NOT NULL COMMENT '位数 1～4',
    sort        INT          NOT NULL DEFAULT 0 COMMENT '在编码中的顺序（从左到右）',
    remark      VARCHAR(256) NULL,
    version     INT          NOT NULL DEFAULT 0,
    created_by  BIGINT       NULL,
    created_at  DATETIME     NOT NULL,
    updated_by  BIGINT       NULL,
    updated_at  DATETIME     NOT NULL,
    deleted     TINYINT      NOT NULL DEFAULT 0
) COMMENT '物料编码段';
CREATE INDEX idx_eng_code_seg_category ON eng_code_segment (category_id);

CREATE TABLE eng_code_segment_value (
    id          BIGINT       NOT NULL PRIMARY KEY,
    segment_id  BIGINT       NOT NULL,
    value_code  VARCHAR(4)   NOT NULL COMMENT '特征值，位数等于编码段位数',
    value_name  VARCHAR(64)  NOT NULL COMMENT '说明，如 UL3302',
    sort        INT          NOT NULL DEFAULT 0,
    status      VARCHAR(16)  NOT NULL DEFAULT 'ENABLED',
    remark      VARCHAR(256) NULL,
    version     INT          NOT NULL DEFAULT 0,
    created_by  BIGINT       NULL,
    created_at  DATETIME     NOT NULL,
    updated_by  BIGINT       NULL,
    updated_at  DATETIME     NOT NULL,
    deleted     TINYINT      NOT NULL DEFAULT 0
) COMMENT '物料编码段特征值';
CREATE INDEX idx_eng_code_segv_segment ON eng_code_segment_value (segment_id);

